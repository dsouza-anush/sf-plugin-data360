import { readFile, writeFile } from 'node:fs/promises';
import { format } from 'prettier';

const root = new URL('../', import.meta.url);
const manifestUrl = new URL('oclif.manifest.json', root);
const outputUrl = new URL('docs/COMMAND_REFERENCE.md', root);
const manifest = JSON.parse(await readFile(manifestUrl, 'utf8'));
const commands = Object.entries(manifest.commands ?? {}).sort(([left], [right]) => left.localeCompare(right));

for (const [id, command] of commands) {
  if (typeof command.summary !== 'string' || command.summary.trim().length === 0) {
    throw new Error(`Manifest command ${id} is missing a summary.`);
  }
  if (typeof command.description !== 'string' || command.description.trim().length === 0) {
    throw new Error(`Manifest command ${id} is missing a description.`);
  }
  if (!Array.isArray(command.examples) || command.examples.length === 0) {
    throw new Error(`Manifest command ${id} is missing examples.`);
  }
}

const inline = (value) =>
  String(value ?? '')
    .replaceAll('|', '\\|')
    .replaceAll('\n', ' ')
    .trim();
const commandName = (id) => `sf ${id.replaceAll(':', ' ')}`;
const renderTemplate = (value, id) =>
  value.replaceAll('<%= config.bin %>', 'sf').replaceAll('<%= command.id %>', id.replaceAll(':', ' '));

const renderArguments = (args) => {
  const entries = Object.entries(args ?? {});
  if (entries.length === 0) return '';
  return [
    '### Arguments',
    '',
    '| Argument | Required | Description |',
    '| --- | --- | --- |',
    ...entries.map(
      ([name, argument]) =>
        `| ${[`\`${name}\``, argument.required ? 'yes' : 'no', inline(argument.description)].join(' | ')} |`
    ),
    '',
  ].join('\n');
};

const renderFlags = (flags) => {
  const entries = Object.entries(flags ?? {}).sort(([left], [right]) => left.localeCompare(right));
  if (entries.length === 0) return '';
  return [
    '### Flags',
    '',
    '| Flag | Required | Description |',
    '| --- | --- | --- |',
    ...entries.map(([name, flag]) => {
      const value = flag.type === 'option' ? '=<value>' : '';
      const short = flag.char ? ` (\`-${flag.char}\`)` : '';
      return `| ${[
        `\`--${name}${value}\`${short}`,
        flag.required ? 'yes' : 'no',
        inline(flag.summary ?? flag.description),
      ].join(' | ')} |`;
    }),
    '',
  ].join('\n');
};

const renderExamples = (examples, id) => {
  if (!Array.isArray(examples) || examples.length === 0) return '';
  const rendered = examples.flatMap((example) => {
    const [explanation, ...commandLines] = renderTemplate(example, id).split('\n');
    return [`- ${explanation}`, '', '  ```shell', ...commandLines.map((line) => `  ${line}`), '  ```', ''];
  });
  return ['### Examples', '', ...rendered].join('\n');
};

const sections = commands.map(([id, command]) => {
  const parts = [`## \`${commandName(id)}\``, '', command.summary, '', command.description, ''];
  const argumentsSection = renderArguments(command.args);
  if (argumentsSection) parts.push(argumentsSection);
  const flagsSection = renderFlags(command.flags);
  if (flagsSection) parts.push(flagsSection);
  const examplesSection = renderExamples(command.examples, id);
  if (examplesSection) parts.push(examplesSection);
  return parts
    .join('\n')
    .replace(/\n{3,}/gu, '\n\n')
    .trimEnd();
});

const output = await format(
  [
    '# Data 360 command reference',
    '',
    '<!-- This file is generated by scripts/generate-command-reference.mjs. Do not edit it by hand. -->',
    '',
    `This reference contains ${commands.length} commands and is generated from the same oclif manifest used by Salesforce CLI. Run \`sf <command> --help\` for the installed version of any command.`,
    '',
    sections.join('\n\n'),
    '',
  ].join('\n'),
  { parser: 'markdown', printWidth: 120 }
);

if (process.argv.includes('--check')) {
  const current = await readFile(outputUrl, 'utf8').catch(() => '');
  if (current !== output) {
    process.stderr.write('docs/COMMAND_REFERENCE.md is stale. Run yarn docs:commands:generate.\n');
    process.exitCode = 1;
  }
} else {
  await writeFile(outputUrl, output);
  process.stdout.write(`Generated docs/COMMAND_REFERENCE.md for ${commands.length} commands.\n`);
}
